// major.minor.build from version.properties; the build number is also the version code.
val versionProps = Properties().apply { rootProject.file("version.properties").inputStream().use { load(it) } }
val appBuild = versionProps.getProperty("build").toInt()
val appVersionName = "${versionProps.getProperty("major")}.${versionProps.getProperty("minor")}.$appBuild"

// The release key lives outside the repository (build-apk.sh makes one the first time).
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
